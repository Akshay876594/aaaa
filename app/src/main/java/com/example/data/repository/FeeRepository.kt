package com.example.data.repository

import com.example.data.local.PaymentReceiptDao
import com.example.data.local.StudentDao
import com.example.data.model.PaymentReceiptEntity
import com.example.data.model.StudentEntity
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.flow.Flow
import kotlinx.coroutines.withContext
import java.util.Locale

class FeeRepository(
    private val studentDao: StudentDao,
    private val paymentReceiptDao: PaymentReceiptDao
) {
    val allStudents: Flow<List<StudentEntity>> = studentDao.getAllStudents()
    val allReceipts: Flow<List<PaymentReceiptEntity>> = paymentReceiptDao.getAllReceipts()

    fun getStudentById(id: Long): Flow<StudentEntity?> = studentDao.getStudentById(id)

    fun getReceiptsForStudent(studentId: Long): Flow<List<PaymentReceiptEntity>> =
        paymentReceiptDao.getReceiptsForStudent(studentId)

    suspend fun addStudent(student: StudentEntity): Long = withContext(Dispatchers.IO) {
        studentDao.insertStudent(student)
    }

    suspend fun updateStudent(student: StudentEntity) = withContext(Dispatchers.IO) {
        studentDao.updateStudent(student)
    }

    suspend fun deleteStudent(student: StudentEntity) = withContext(Dispatchers.IO) {
        studentDao.deleteStudent(student)
    }

    suspend fun recordPayment(
        studentId: Long,
        amount: Double,
        paymentMethod: String,
        referenceNumber: String,
        notes: String
    ): Result<PaymentReceiptEntity> = withContext(Dispatchers.IO) {
        try {
            val student = studentDao.getStudentByIdDirect(studentId)
                ?: return@withContext Result.failure(IllegalArgumentException("Student not found"))

            val prevBalance = student.outstandingBalance
            val newPaidTotal = student.paidAmount + amount
            val remainingBal = (student.netFee - newPaidTotal).coerceAtLeast(0.0)

            val nextId = (paymentReceiptDao.getMaxReceiptId() ?: 0L) + 1L
            val receiptNumber = String.format(Locale.US, "REC-2026-%04d", nextId)

            val receipt = PaymentReceiptEntity(
                receiptId = 0, // Auto-generated by Room
                receiptNumber = receiptNumber,
                studentId = student.id,
                studentName = student.fullName,
                studentRollNumber = student.studentId,
                studentGrade = student.grade,
                amountPaid = amount,
                paymentMethod = paymentMethod,
                referenceNumber = if (referenceNumber.isBlank()) "TXN-${System.currentTimeMillis().toString().takeLast(8)}" else referenceNumber,
                paymentDateEpoch = System.currentTimeMillis(),
                previousBalance = prevBalance,
                remainingBalance = remainingBal,
                notes = notes,
                issuedBy = "ScholarFee Financial Office"
            )

            val insertedReceiptId = paymentReceiptDao.insertReceipt(receipt)
            studentDao.updatePaidAmount(student.id, newPaidTotal)

            val finalReceipt = receipt.copy(receiptId = insertedReceiptId)
            Result.success(finalReceipt)
        } catch (e: Exception) {
            Result.failure(e)
        }
    }
}
